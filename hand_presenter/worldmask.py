def is_land(lat: float, lon: float) -> bool:
    x = min(MASK_W - 1, max(0, int((lon + 180) / 360 * MASK_W)))
    y = min(MASK_H - 1, max(0, int((90 - lat) / 180 * MASK_H)))
    i = y * MASK_W + x
    return bool((_MASK[i >> 3] >> (7 - (i & 7))) & 1)
